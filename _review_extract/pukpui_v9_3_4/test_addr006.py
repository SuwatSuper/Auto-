# -*- coding: utf-8 -*-
"""test_addr006.py — [B2] negative fixture: ADDR006 รหัสไปรษณีย์ ↔ จังหวัด ไม่สอดคล้อง

ไม่พึ่ง corpus จริง. ตรึง:
  • จังหวัดเชียงใหม่ + ไปรษณีย์ 10xxx (กรุงเทพ) → ADDR006 ยิง
  • จังหวัด + ไปรษณีย์สอดคล้อง (เชียงใหม่ 50xxx/58xxx) → เงียบ
  • กรุงเทพฯ (ADDR005 ดูแล) → ADDR006 ไม่ยิง (กันทับซ้อน)
  • ดึงจังหวัดไม่ได้ / ไม่มีไปรษณีย์ → เงียบ (conservative)
  • มีไปรษณีย์ที่ถูกต้องอยู่ด้วย → เงียบ
  • prefix ที่ครอบหลายจังหวัด (สมุทรปราการ 10xxx) → ไม่ฟ้องผิด

exit 0 = ผ่าน, 1 = พบปัญหา.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from rules_engine import r_addr006

_fail = 0


def _check(label, cond):
    global _fail
    print(("  [PASS] " if cond else "  [FAIL] ") + label)
    if not cond:
        _fail += 1


def _fires(addr):
    return bool(r_addr006({"address": addr}, None, {}))


# 1) ขัดกันชัด: เชียงใหม่ + 10250 (กรุงเทพ) → ยิง
_check("เชียงใหม่ + ไปรษณีย์ 10250 (กรุงเทพ) → ADDR006 ยิง",
       _fires("99/1 ถนนนิมมาน ตำบลสุเทพ อำเภอเมือง จังหวัดเชียงใหม่ 10250"))
_d = r_addr006({"address": "ถนนนิมมาน จังหวัดเชียงใหม่ 10250"}, None, {})[0]
_check("detail ระบุไปรษณีย์ + จังหวัดที่ขัด", "10250" in _d and "เชียงใหม่" in _d)

# 2) สอดคล้อง → เงียบ (เชียงใหม่ใช้ทั้ง 50/58)
_check("เชียงใหม่ + 50000 → เงียบ", not _fires("จังหวัดเชียงใหม่ 50000"))
_check("เชียงใหม่ + 58130 (อำเภอที่ใช้ prefix 58) → เงียบ", not _fires("อ.จอมทอง จังหวัดเชียงใหม่ 58130"))

# 3) จังหวัดอื่นขัด: นนทบุรี (11) + 30000 (นครราชสีมา) → ยิง
_check("นนทบุรี + 30000 (โคราช) → ยิง", _fires("99 หมู่ 2 นนทบุรี 30000"))

# 4) กรุงเทพฯ → ADDR006 เว้น (ADDR005 ดูแล) — กันทับซ้อน
_check("กรุงเทพมหานคร + 50000 → ADDR006 เงียบ (ADDR005 ดูแล)",
       not _fires("1 ถนนสุขุมวิท กรุงเทพมหานคร 50000"))
_check("กทม. + 50000 → ADDR006 เงียบ", not _fires("1 ถนน กทม. 50000"))

# 5) conservative: ดึงจังหวัดไม่ได้ / ไม่มีไปรษณีย์ → เงียบ
_check("ไม่ระบุจังหวัด → เงียบ", not _fires("99 หมู่ 1 ถนนสายเอเชีย 50000"))
_check("ไม่มีไปรษณีย์ 5 หลัก → เงียบ", not _fires("99 จังหวัดเชียงใหม่"))
_check("ที่อยู่ว่าง → เงียบ", not _fires(""))

# 6) prefix หลายจังหวัด: สมุทรปราการ ใช้ 10xxx จริง → ไม่ฟ้องผิด
_check("สมุทรปราการ + 10270 (prefix 10 ถูกต้องของสมุทรปราการ) → เงียบ",
       not _fires("99 หมู่ 5 บางพลี สมุทรปราการ 10270"))

# 7) มีไปรษณีย์ที่สอดคล้องอยู่ด้วย → เงียบ (กันฟ้องจากเลข 5 หลักอื่นในที่อยู่)
_check("มีทั้งเลข 5 หลักมั่ว + ไปรษณีย์จริงที่ตรงจังหวัด → เงียบ",
       not _fires("เลขที่ 12345 ถนนข จังหวัดเชียงใหม่ 50200"))

print("=" * 60)
if _fail == 0:
    print("RESULT: [PASS] ADDR006 ยิงเมื่อไปรษณีย์↔จังหวัดขัดชัด + เงียบทุกเคส benign/ทับซ้อน")
    sys.exit(0)
print(f"RESULT: [FAIL] {_fail} ข้อไม่ผ่าน")
sys.exit(1)
